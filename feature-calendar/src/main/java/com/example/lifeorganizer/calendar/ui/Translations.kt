    fun get(key: TransKey, lang: String): String {
        val map = when (lang) {
            "de" -> de
            "tr" -> tr
            "es" -> es
            "zh" -> zh
            else -> en
        }
        return map[key] ?: en[key] ?: key.name
    }
}

@Composable
fun stringTrans(key: TransKey, viewModel: MainViewModel): String {
    val lang by viewModel.languageCode.collectAsState()
    return Translations.get(key, lang)
}
